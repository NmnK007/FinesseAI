import { test,before,after } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readdir,readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import type { Database,Sql } from '../src/lib/db';
import { businessStore } from '../src/lib/db/businesses';
import { lendingStore } from '../src/lib/db/lending';
let pg:PGlite,db:Database;
const owner={id:randomUUID(),email:'owner@finnese.test',role:'customer' as const};
const other={id:randomUUID(),email:'other@finnese.test',role:'customer' as const};
const reviewer={id:randomUUID(),email:'reviewer@finnese.test',role:'lender' as const};
before(async()=>{pg=new PGlite();for(const f of(await readdir('db/migrations')).sort())await pg.exec(await readFile(`db/migrations/${f}`,'utf8'));db={query:(s,p)=>pg.query(s,p),transaction:fn=>pg.transaction(tx=>fn(tx as Sql))};for(const u of[owner,other,reviewer])await db.query('INSERT INTO users(id,email,role) VALUES ($1,$2,$3)',[u.id,u.email,u.role]);});
after(async()=>pg.close());
test('reviewer role alone grants no records; owner grant, expiry and revocation are enforced',async()=>{
 const business=await businessStore(db).create(owner,'Shared fictional business'),store=lendingStore(db);
 assert.equal((await store.pipeline(reviewer)).length,0);
 await assert.rejects(store.review(reviewer,business.id,'2026-11-13'),/grant/);
 await assert.rejects(store.share(other,business.id,reviewer.email),/access/);
 await assert.rejects(store.share(owner,business.id,other.email),/enrolled/);
 await store.share(owner,business.id,reviewer.email);
 assert.equal((await store.pipeline(reviewer)).length,1);
 assert.equal((await store.review(reviewer,business.id,'2026-11-13')).card.overall,null);
 await assert.rejects(store.review(other,business.id,'2026-11-13'),/role/);
 await store.note(reviewer,business.id,'NEEDS_INFORMATION','Please supply complete account coverage.');
 assert.equal((await store.review(reviewer,business.id,'2026-11-13')).notes.length,1);
 await db.query("UPDATE sharing_grants SET expires_at=now()-interval '1 second' WHERE business_id=$1",[business.id]);
 await assert.rejects(store.review(reviewer,business.id,'2026-11-13'),/grant/);
 await store.share(owner,business.id,reviewer.email);
 const grant=(await store.owner(owner,business.id)).grants[0];await store.revoke(owner,business.id,String(grant.id));
 await assert.rejects(store.note(reviewer,business.id,'REVIEWED','Review must fail after revocation'),/grant/);
 assert.equal((await store.pipeline(reviewer)).length,0);
});
test('sandbox drafts persist exact illustrative terms and never transmit applications',async()=>{
 const business=await businessStore(db).create(owner,'Sandbox example'),store=lendingStore(db);
 await assert.rejects(store.create(other,business.id,'ILLUSTRATIVE_A',10000000,12),/access/);
 const draft=await store.create(owner,business.id,'ILLUSTRATIVE_A',10000000,12);
 assert.equal(draft.terms.mode,'SIMULATED');assert.equal(draft.terms.apr,null);assert.equal(draft.terms.notAnOffer,true);assert.equal(draft.terms.emiPaise,888488);
 assert.equal(draft.terms.totalRepaymentPaise,888488*12+50000);
 await assert.rejects(store.transition(other,business.id,draft.id,'SIMULATED_SUBMISSION'),/access/);
 assert.equal((await store.transition(owner,business.id,draft.id,'SIMULATED_SUBMISSION')).transmitted,false);
 await assert.rejects(store.transition(owner,business.id,draft.id,'CANCELLED'),/already finalized/);
 assert.equal((await store.owner(owner,business.id)).applications[0].status,'SIMULATED_SUBMISSION');
});
